# Ask the user to enter a whole number
num1 = int(input("Enter a number= "))

# Calculate the square of the number 
square = num1**2

# Calculate the cube of the number 
cube = num1**3

# Find the remainder when dividing by 2 (0 = even, 1 = odd)
remainder = num1%2

# Print all three results with clear labels
print("Square =",square) 
print("Cube =", cube) 
print("Remainder =", remainder)

#Example output
#Enter a number= 6
# Square = 36
# Cube = 216
# Remainder = 0 (so it was even number)