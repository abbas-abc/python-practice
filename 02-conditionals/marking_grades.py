percentage = int(input("How many percentage you got in Math? " ))
if percentage >= 80:
    print("You got A grade.")  #we add 4 conditions to give the grade according to the percentage in the subject 
elif percentage >= 70:
    print("You got B grade")
elif percentage >= 60:
    print("You got C grade")
elif percentage >= 50:
    print("You got C grade")

else:
    print("You fail this subject.")

