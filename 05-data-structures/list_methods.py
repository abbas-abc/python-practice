nums = [1,6,5,3,4]

# This will add the number at the last of the list
nums.append(10)
print(nums)

#it insert the specific value of specific index number
nums.insert(2,11)
print(nums)

# It makes the whole list in reverse order
nums.reverse()
print(nums)

# It makes the numbers in ascending order
nums.sort()
print(nums)

# It makes the numbers in descending order
nums.sort(reverse=True)
print(nums)


